package com.nexio.build.integrationaudit

import java.io.File

class IntegrationAuditReportWriter(
    private val outputDir: File
) {
    fun writeMarkdownReport(
        runtimeEventFixtureFile: File,
        providers: List<IntegrationAuditProviderRow>,
        specs: List<IntegrationAuditSpecRow>,
        violations: List<IntegrationAuditViolation>,
        exemptions: List<IntegrationAuditExemption>,
        expectedShapes: Map<String, Map<String, String>>,
        contractShapes: Map<String, Map<String, String>>,
        cacheContracts: Map<String, Map<String, String>>,
        metadataRouterPrerequisiteShapeIds: Set<String>,
        bestPracticeRuleSupport: Map<String, BestPracticeRuleSupport>,
        providerContractRows: List<IntegrationProviderContractProvenanceRow>,
        gitSha: String,
        gitWorktreeState: GitWorktreeState
    ) {
        require(runtimeEventFixtureFile.isFile) {
            "Runtime event sample was not generated by runtime tests: $runtimeEventFixtureFile"
        }
        writeIntegrationRuntimeAudit(
            outputDir = outputDir,
            runtimeEventFixtureFile = runtimeEventFixtureFile,
            providers = providers,
            specs = specs,
            violations = violations,
            exemptions = exemptions,
            expectedShapes = expectedShapes,
            contractShapes = contractShapes,
            cacheContracts = cacheContracts,
            metadataRouterPrerequisiteShapeIds = metadataRouterPrerequisiteShapeIds,
            bestPracticeRuleSupport = bestPracticeRuleSupport,
            providerContractRows = providerContractRows,
            gitSha = gitSha,
            gitWorktreeState = gitWorktreeState
        )
    }

    fun writeJsonReport() {
        check(outputDir.resolve("integration-runtime-audit.json").isFile) {
            "Integration audit JSON was not written."
        }
    }
}
